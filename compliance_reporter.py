class ComplianceReporter:
    def __init__(self, log_file=None):
        self.log_file = log_file or cfg.LOG_CSV

    def generate_report(self, output_file="compliance_audit.html"):
        """Generates a summary HTML report for compliance auditing."""
        log_count = 0
        log_size = 0.0
        first_event = "N/A"
        last_event = "N/A"

        if os.path.exists(self.log_file):
            log_size = round(os.path.getsize(self.log_file) / (1024 * 1024), 2)
            try:
                # Read just enough to get the count and dates
                df = pd.read_csv(self.log_file, usecols=['Timestamp'], on_bad_lines='skip', low_memory=False)
                log_count = len(df)
                if not df.empty:
                    first_event = str(df['Timestamp'].iloc[0])
                    last_event = str(df['Timestamp'].iloc[-1])
            except Exception as e:
                log.warning(f"Could not parse log file for compliance report: {e}")

        html_content = COMPLIANCE_HTML_TEMPLATE.format(
            date_generated=datetime.datetime.now().strftime('%Y-%m-%d %H:%M:%S'),
            version=cfg.VERSION,
            log_count=f"{log_count:,}",
            log_size=log_size,
            first_event=first_event,
            last_event=last_event
        )

        try:
            with open(output_file, 'w', encoding='utf-8') as f:
                f.write(html_content)
            log.info(f"Compliance report generated: {output_file}")
            return output_file
        except Exception as e:
            log.error(f"Failed to generate compliance report: {e}")
            return None

if __name__ == "__main__":
    reporter = ComplianceReporter()
